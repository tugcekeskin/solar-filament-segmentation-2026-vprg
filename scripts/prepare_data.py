"""G1 data pipeline CLI. Run from repo root: .venv/bin/python scripts/prepare_data.py --all"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from filseg import data as D  # noqa: E402

RES = (1024, 1280, 1536)


def do_manifest(coco):
    df = D.build_manifest(coco)
    Path("data/processed").mkdir(parents=True, exist_ok=True)
    df.to_csv("data/processed/manifest.csv", index=False)
    print(f"manifest: {len(df)} views, {df.stem.nunique()} stems, {int(df.n_ann.sum())} annotations, "
          f"{df.date.nunique()} dates, {df.annotator.nunique()} annotators")
    print("views per stem:", df.drop_duplicates('stem').n_views_of_stem.value_counts().sort_index().to_dict())
    return df


def do_split(df):
    sp = D.make_split(sorted(df.stem.unique()))
    Path("data/splits").mkdir(parents=True, exist_ok=True)
    Path("data/splits/split_v1.json").write_text(json.dumps(sp, indent=1))
    f = pd.Series(sp["folds"])
    print("stems per fold:", f.value_counts().sort_index().to_dict())
    yr = pd.crosstab(f.index.str[:4], f.values)
    print("stems by year x fold:\n", yr.to_string())
    print(f"train stems {len(sp['train'])}, val stems {len(sp['val'])}, no date/stem leakage: OK")
    return sp


def do_yolo(coco, sp):
    c = D.write_yolo_dataset(coco, sp, Path("data/yolo/v1"))
    n_views = c["train_views"] + c["val_views"]
    print("yolo:", c, "total views", n_views)
    bad = 0
    for p in Path("data/yolo/v1/labels").rglob("*.txt"):
        for line in p.read_text().splitlines():
            try:
                D.parse_yolo_line(line)
            except ValueError:
                bad += 1
    print("unparseable label lines:", bad)
    assert n_views == len(coco["images"]) and bad == 0
    return c


def fmt_stats_table(df):
    lines = ["| target | mean | median | p5 | min | frac<0.5 | frac<0.8 |", "|---|---|---|---|---|---|---|"]
    for name, col in [("YOLO label round-trip @2048", "iou_yolo")] + [(f"train res {r}", f"iou_{r}") for r in RES]:
        s = D.iou_stats(df[col])
        lines.append(f"| {name} | {s['mean']:.4f} | {s['median']:.4f} | {s['p5']:.4f} | {s['min']:.4f} | "
                     f"{s['lt05']:.4f} | {s['lt08']:.4f} |")
    return "\n".join(lines)


def do_audit(coco, sp, skipped):
    r = D.run_audit(coco, Path("data/yolo/v1"), sp, RES)
    df, agree = r["df"], r["agree"]
    df.to_csv("data/processed/fidelity.csv", index=False)
    table = fmt_stats_table(df)
    a = df.area_px
    area = (f"min {a.min()}, median {a.median():.0f}, p95 {a.quantile(.95):.0f}, max {a.max()}")
    w = df.width_est
    thin = (f"Estimated mean width (2*area/perimeter): median {w.median():.1f} px, p5 {w.quantile(.05):.1f} px; "
            f"{(w < 4).mean():.1%} of annotations have width < 4 px (< 2 px at 1024), "
            f"{(w < 6).mean():.1%} < 6 px.")
    by_res = {}
    for res in RES:
        thin_m = df[w < 4][f"iou_{res}"].mean() if (w < 4).any() else float("nan")
        by_res[res] = thin_m
    thin_tbl = "; ".join(f"{k}: {v:.3f}" for k, v in by_res.items())
    ag_pq_mean = agree.pq.mean()
    pooled = agree.sum_iou.sum() / (agree.tp.sum() + .5 * agree.fp.sum() + .5 * agree.fn.sum())
    n_stems = df.view_id.str.split("-").str[1].nunique()
    md = f"""# G1 Data report

Generated by `scripts/prepare_data.py --all` (deterministic).

## Dataset summary
- {len(coco['images'])} views, {n_stems} stems, {len(coco['annotations'])} annotations
- Split `data/splits/split_v1.json`: group key = date, seed 42, 5 folds, val = fold 0
  ({len(sp['train'])} train / {len(sp['val'])} val stems)
- YOLO dataset `data/yolo/v1` (single class `filament`, one symlink + label file per view); polygons skipped (<3 distinct points): {skipped}

## Conversion fidelity (IoU vs. pycocotools mask of original polygon at 2048x2048)
{table}

Training-resolution rows: polygon rasterized at res, nearest-upsampled to 2048 (upper bound on what a
model trained at that imgsz can represent). Per-annotation values in `data/processed/fidelity.csv`.

## Area / thin structures
Area (pixels at 2048): {area}.

{thin}

Mean IoU of thin annotations (width < 4 px) per resolution: {thin_tbl}.

## Within-view instance overlaps
{r['overlaps']} annotation pairs with mask IoU > 0 within the same view.

## Inter-annotator agreement (stems with >= 2 views)
{len(agree)} view pairs. Greedy one-to-one match at IoU > 0.5, PQ = sum IoU(TP) / (TP + FP/2 + FN/2),
one annotator as GT and the other as prediction (symmetric).
- Mean per-pair PQ: {ag_pq_mean:.4f} (median {agree.pq.median():.4f})
- Pooled PQ over all pairs: {pooled:.4f}

This is an upper-bound reference for model PQ (organizer score uses the no-Hungarian matching, which differs slightly).
"""
    Path("docs/G1_data_report.md").write_text(md)
    print(table)
    print("area:", area)
    print(thin)
    print("thin IoU by res:", thin_tbl)
    print("within-view overlapping pairs:", r["overlaps"])
    print(f"inter-annotator: {len(agree)} pairs, mean PQ {ag_pq_mean:.4f}, pooled {pooled:.4f}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", action="store_true")
    ap.add_argument("--split", action="store_true")
    ap.add_argument("--yolo", action="store_true")
    ap.add_argument("--audit", action="store_true")
    ap.add_argument("--all", action="store_true")
    a = ap.parse_args()
    if not any(vars(a).values()):
        ap.error("choose a step or --all")
    coco = D.load_coco()
    df = do_manifest(coco) if (a.manifest or a.all) else D.build_manifest(coco)
    sp = None
    if a.split or a.all:
        sp = do_split(df)
    elif a.yolo or a.audit:
        sp = json.loads(Path("data/splits/split_v1.json").read_text())
    c = do_yolo(coco, sp) if (a.yolo or a.all) else None
    if a.audit or a.all:
        skipped = c["skipped"] if c else "see yolo step"
        do_audit(coco, sp, skipped)


if __name__ == "__main__":
    main()
